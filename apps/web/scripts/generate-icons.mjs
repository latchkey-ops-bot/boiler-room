#!/usr/bin/env node
// Turns the design system's pixel icons into path data for <Icon>.
//
//   node scripts/generate-icons.mjs <boiler-room-design>/design-system/icons
//
// Each icon is a 12 by 12 grid of rects in currentColor. Run it again when the design repo adds or
// redraws an icon, and commit src/components/icons.generated.ts.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/generate-icons.mjs <path to design-system/icons>');
  process.exit(1);
}

const icons = {};
for (const file of readdirSync(dir)
  .filter((name) => name.endsWith('.svg'))
  .sort()) {
  const svg = readFileSync(join(dir, file), 'utf8');
  if (!svg.includes('viewBox="0 0 12 12"')) throw new Error(`${file} is not on the 12 by 12 grid`);
  const rects = [...svg.matchAll(/<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"/g)];
  if (rects.length === 0) throw new Error(`${file} has no pixels`);
  icons[basename(file, '.svg')] = rects
    .map(([, x, y, w, h]) => `M${x} ${y}h${w}v${h}h-${w}z`)
    .join('');
}

const out = new URL('../src/components/icons.generated.ts', import.meta.url);
const body = Object.entries(icons)
  .map(([name, d]) => `  ${/^[a-z]+$/.test(name) ? name : `'${name}'`}: '${d}',`)
  .join('\n');
writeFileSync(
  out,
  `// Generated by scripts/generate-icons.mjs from the design system's icons. Do not edit.\n\nexport const ICON_PATHS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${Object.keys(icons).length} icons to src/components/icons.generated.ts`);
